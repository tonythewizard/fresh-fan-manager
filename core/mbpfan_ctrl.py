"""
mbpfan control layer. All write operations are routed through the
pkexec helper at /usr/local/bin/macfan-helper.
"""
from __future__ import annotations

import configparser
import io
import os
import shutil
import subprocess
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Optional

MBPFAN_BIN = "mbpfan"
MBPFAN_CONF = Path("/etc/mbpfan.conf")
HELPER_BIN = "/usr/local/bin/macfan-helper"

def _get_helper() -> str:
    for h in ("/usr/local/bin/freshfan-helper", "/usr/local/bin/macfan-helper"):
        if Path(h).exists():
            return h
    return HELPER_BIN


@dataclass
class MbpfanConfig:
    low_temp: int = 55
    high_temp: int = 66
    max_temp: int = 86
    polling_interval: int = 7
    min_fan1_speed: Optional[int] = None
    max_fan1_speed: Optional[int] = None

    def to_conf_text(self) -> str:
        lines = [
            "# Generated by Fresh Fan Manager",
            "[general]",
            f"low_temp = {self.low_temp}",
            f"high_temp = {self.high_temp}",
            f"max_temp = {self.max_temp}",
            f"polling_interval = {self.polling_interval}",
        ]
        if self.min_fan1_speed is not None:
            lines.append(f"min_fan1_speed = {self.min_fan1_speed}")
        if self.max_fan1_speed is not None:
            lines.append(f"max_fan1_speed = {self.max_fan1_speed}")
        return "\n".join(lines) + "\n"


# Sensible presets for the MacBookAir7,2 (fan range 1200-6500 RPM)
PRESETS = {
    "Silent": MbpfanConfig(low_temp=58, high_temp=72, max_temp=88, polling_interval=10,
                           min_fan1_speed=1200, max_fan1_speed=4500),
    "Balanced": MbpfanConfig(low_temp=44, high_temp=58, max_temp=76, polling_interval=7,
                             min_fan1_speed=1500, max_fan1_speed=6500),
    "Performance": MbpfanConfig(low_temp=42, high_temp=58, max_temp=80, polling_interval=4,
                                min_fan1_speed=2500, max_fan1_speed=6500),
}


def is_installed() -> bool:
    if shutil.which(MBPFAN_BIN) is not None:
        return True
    # Fallback: when launched from a GUI session, /usr/sbin may not be in PATH.
    # mbpfan typically lives in /usr/sbin/mbpfan on Debian/Parrot.
    for p in ("/usr/sbin/mbpfan", "/usr/bin/mbpfan",
              "/usr/local/sbin/mbpfan", "/usr/local/bin/mbpfan",
              "/sbin/mbpfan"):
        if Path(p).is_file():
            return True
    return False


def service_status() -> str:
    """Returns 'active', 'inactive', 'failed', or 'not-found'."""
    try:
        r = subprocess.run(
            ["systemctl", "is-active", "mbpfan"],
            capture_output=True, text=True, timeout=3,
        )
        out = r.stdout.strip()
        if out in ("active", "inactive", "failed", "activating", "deactivating"):
            return out
        if r.returncode == 4:
            return "not-found"
        return out or "unknown"
    except Exception:
        return "unknown"


def service_enabled() -> bool:
    try:
        r = subprocess.run(
            ["systemctl", "is-enabled", "mbpfan"],
            capture_output=True, text=True, timeout=3,
        )
        return r.stdout.strip() == "enabled"
    except Exception:
        return False


def read_config() -> MbpfanConfig:
    """Parse /etc/mbpfan.conf. Missing fields fall back to defaults."""
    cfg = MbpfanConfig()
    if not MBPFAN_CONF.exists():
        return cfg
    parser = configparser.ConfigParser(inline_comment_prefixes=("#", ";"))
    try:
        parser.read(MBPFAN_CONF)
    except Exception:
        return cfg
    if "general" not in parser:
        return cfg
    g = parser["general"]
    def get_int(key: str, default):
        try:
            return int(g.get(key, str(default)))
        except (ValueError, TypeError):
            return default
    cfg.low_temp = get_int("low_temp", cfg.low_temp)
    cfg.high_temp = get_int("high_temp", cfg.high_temp)
    cfg.max_temp = get_int("max_temp", cfg.max_temp)
    cfg.polling_interval = get_int("polling_interval", cfg.polling_interval)
    if "min_fan1_speed" in g:
        cfg.min_fan1_speed = get_int("min_fan1_speed", None)
    if "max_fan1_speed" in g:
        cfg.max_fan1_speed = get_int("max_fan1_speed", None)
    return cfg


# ---------------------------------------------------------------------------
# Helper-routed write operations
# ---------------------------------------------------------------------------

def _run_helper(args: list[str], input_text: Optional[str] = None,
                timeout: int = 60) -> tuple[bool, str]:
    """Run the helper via pkexec. Returns (ok, output)."""
    helper = _get_helper()
    if not Path(helper).exists():
        return False, f"Helper not found at {helper}. Run install.sh first."
    try:
        r = subprocess.run(
            ([helper] if os.geteuid() == 0 else ["pkexec", "--disable-internal-agent", helper]) + args,
            input=input_text,
            capture_output=True, text=True, timeout=timeout,
        )
        ok = r.returncode == 0
        return ok, (r.stdout + r.stderr).strip()
    except subprocess.TimeoutExpired:
        return False, "Helper timed out."
    except Exception as e:
        return False, f"Helper error: {e}"


def write_config(cfg: MbpfanConfig) -> tuple[bool, str]:
    return _run_helper(["write-conf"], input_text=cfg.to_conf_text())


def restart_service() -> tuple[bool, str]:
    ok, msg = _run_helper(["restart-mbpfan"])
    if not ok:
        low = msg.lower()
        if "start-limit" in low or "too often" in low or "too many" in low:
            return False, ("Troppi riavvii ravvicinati. Attendi qualche secondo "
                           "e riprova. (systemd start-limit)")
    return ok, msg


def enable_service() -> tuple[bool, str]:
    return _run_helper(["enable-mbpfan"])


def install_mbpfan() -> tuple[bool, str]:
    return _run_helper(["install-mbpfan"], timeout=180)


# --------------------------------------------------------------------------
# Universal Hardware Backend Detection
# --------------------------------------------------------------------------

def has_thinkpad() -> bool:
    """Lenovo ThinkPad ACPI fan control."""
    return Path("/proc/acpi/ibm/fan").exists()


def has_asus_wmi() -> bool:
    """ASUS WMI laptop thermal policies."""
    return (Path("/sys/devices/platform/asus-nb-wmi/throttle_thermal_policy").exists() or
            Path("/sys/devices/platform/asus-nb-wmi/fan_boost_mode").exists())


def has_dell() -> bool:
    """Dell laptop thermal management."""
    return Path("/sys/devices/platform/dell-laptop/thermal_profile").exists()


def find_generic_pwm() -> Optional[tuple[str, int]]:
    """Returns (hwmon_name, pwm_idx) for the first writable PWM controller."""
    for hw in sorted(Path("/sys/class/hwmon").glob("hwmon*")):
        for pwm in sorted(hw.glob("pwm[1-9]")):
            try:
                idx = int(pwm.name.replace("pwm", ""))
                return hw.name, idx
            except ValueError:
                continue
    return None


def find_smc_path() -> Optional[Path]:
    """Find the Apple SMC sysfs directory dynamically."""
    candidates = [
        Path("/sys/devices/platform/applesmc.768"),
        Path("/sys/devices/platform/applesmc"),
    ]
    for c in candidates:
        if c.exists() and (c / "fan1_manual").exists():
            return c
    for hw in Path("/sys/class/hwmon").glob("hwmon*"):
        try:
            if (hw / "name").read_text().strip() == "applesmc" and (hw / "fan1_manual").exists():
                return hw
        except Exception:
            pass
    for c in candidates:
        if c.exists():
            return c
    return None


def has_applesmc() -> bool:
    """True if direct Apple SMC fan control is available in sysfs."""
    p = find_smc_path()
    return p is not None and (p / "fan1_manual").exists()


def has_macsmc() -> bool:
    """True if Apple SMC is managed by the macsmc driver (/dev/smc)."""
    try:
        from core.macsmc import has_macsmc as _has_macsmc
        return _has_macsmc()
    except Exception:
        return False


def get_backend() -> str:
    """Returns 'thinkpad', 'asus_wmi', 'dell', 'applesmc', 'macsmc', 'hwmon_pwm', 'mbpfan', or 'firmware'."""
    # 1. Lenovo ThinkPad
    if has_thinkpad():
        return "thinkpad"

    # 2. ASUS laptops
    if has_asus_wmi():
        return "asus_wmi"

    # 3. Dell laptops
    if has_dell():
        return "dell"

    # 4. Apple SMC (sysfs applesmc)
    if has_applesmc():
        stat = service_status()
        if is_installed() and stat == "active":
            return "mbpfan"
        return "applesmc"

    # 4b. Apple SMC (modern macsmc driver /dev/smc on Linux >= 6.13 / CachyOS / Asahi)
    if has_macsmc():
        return "macsmc"

    # 5. Generic Linux PWM (Framework, HP, Tuxedo, Clevo, desktop motherboards)
    pwm = find_generic_pwm()
    if pwm is not None:
        return "hwmon_pwm"

    # 6. mbpfan daemon
    stat = service_status()
    if is_installed() and stat in ("active", "inactive"):
        return "mbpfan"

    # 7. Safe Firmware fallback
    return "firmware"


def can_control_fan() -> bool:
    """True if active cooling control is available on this hardware."""
    backend = get_backend()
    return backend in ("thinkpad", "asus_wmi", "dell", "applesmc", "macsmc", "hwmon_pwm", "mbpfan")


def get_backend_description() -> str:
    from core.i18n import tr
    backend = get_backend()
    descriptions = {
        "thinkpad": "Lenovo ThinkPad ACPI",
        "asus_wmi": "ASUS WMI Thermal Policy",
        "dell": "Dell Thermal Management",
        "applesmc": tr("backend_applesmc"),
        "macsmc": "Apple SMC (macsmc driver)",
        "hwmon_pwm": tr("backend_hwmon"),
        "mbpfan": tr("backend_mbpfan"),
        "firmware": tr("backend_firmware"),
    }
    return descriptions.get(backend, tr("backend_firmware"))


def apply_preset(name: str) -> tuple[bool, str]:
    if name not in PRESETS:
        return False, f"Unknown preset {name}"
    cfg = PRESETS[name]
    backend = get_backend()

    if backend == "thinkpad":
        level_map = {"Silent": "2", "Balanced": "4", "Performance": "7"}
        return _run_helper(["set-thinkpad-fan", level_map.get(name, "auto")])

    elif backend == "asus_wmi":
        mode_map = {"Silent": "2", "Balanced": "0", "Performance": "1"}
        return _run_helper(["set-asus-profile", mode_map.get(name, "0")])

    elif backend == "dell":
        dell_map = {"Silent": "quiet", "Balanced": "balanced", "Performance": "performance"}
        return _run_helper(["set-dell-profile", dell_map.get(name, "balanced")])

    elif backend == "hwmon_pwm":
        pwm = find_generic_pwm()
        if pwm is None:
            return False, "No PWM device found"
        hw_name, pwm_idx = pwm
        pwm_map = {"Silent": "75", "Balanced": "140", "Performance": "240"}
        ok, msg = _run_helper(["set-pwm-enable", hw_name, str(pwm_idx), "1"])
        if not ok:
            return False, msg
        return _run_helper(["set-pwm", hw_name, str(pwm_idx), pwm_map.get(name, "140")])

    elif backend == "mbpfan":
        ok, msg = write_config(cfg)
        if not ok:
            return ok, msg
        return restart_service()

    elif backend == "applesmc":
        if is_manual_active(1) and cfg.min_fan1_speed:
            return set_manual_rpm(cfg.min_fan1_speed, 1)
        return True, "ok"

    elif backend == "macsmc":
        min_speed = cfg.min_fan1_speed or 1500
        return manual_on(min_speed, 1)

    return True, "Firmware automatic"


# --------------------------------------------------------------------------
# Universal Manual Fan Override
# --------------------------------------------------------------------------

def is_manual_active(fan_idx: int = 1) -> bool:
    """Read the kernel's fan manual flag straight from sysfs/procfs or /dev/smc."""
    backend = get_backend()
    if backend == "thinkpad":
        tp = Path("/proc/acpi/ibm/fan")
        if tp.exists():
            for line in tp.read_text().splitlines():
                if line.startswith("level:"):
                    return line.split(":")[1].strip().lower() != "auto"
        return False
    elif backend == "hwmon_pwm":
        pwm = find_generic_pwm()
        if pwm:
            hw_name, pwm_idx = pwm
            en = Path(f"/sys/class/hwmon/{hw_name}/pwm{pwm_idx}_enable")
            if en.exists():
                return en.read_text().strip() == "1"
        return False
    elif backend == "macsmc":
        try:
            from core.macsmc import query_fans
            fans = query_fans()
            for f in fans:
                if f.index == fan_idx:
                    return f.manual
        except Exception:
            pass
        return False

    smc = find_smc_path()
    if smc is None:
        return False
    p = smc / f"fan{fan_idx}_manual"
    try:
        return p.read_text().strip() == "1"
    except Exception:
        return False


def manual_on(rpm: int, fan_idx: int = 1) -> tuple[bool, str]:
    backend = get_backend()
    if backend == "thinkpad":
        lvl = min(7, max(1, int(rpm * 7 / 5500 if rpm > 100 else rpm * 7 / 100)))
        return _run_helper(["set-thinkpad-fan", str(lvl)])

    elif backend == "asus_wmi":
        mode = "2" if rpm < 2500 else ("1" if rpm > 4500 else "0")
        return _run_helper(["set-asus-profile", mode])

    elif backend == "dell":
        mode = "quiet" if rpm < 2500 else ("performance" if rpm > 4500 else "balanced")
        return _run_helper(["set-dell-profile", mode])

    elif backend == "hwmon_pwm":
        pwm = find_generic_pwm()
        if pwm:
            hw_name, pwm_idx = pwm
            pwm_val = min(255, max(0, int(rpm if rpm <= 255 else rpm * 255 / 6000)))
            ok, msg = _run_helper(["set-pwm-enable", hw_name, str(pwm_idx), "1"])
            if not ok:
                return False, msg
            return _run_helper(["set-pwm", hw_name, str(pwm_idx), str(pwm_val)])

    elif backend == "macsmc":
        return _run_helper(["manual-on-macsmc", str(fan_idx), str(rpm)])

    return _run_helper(["manual-on", str(fan_idx), str(rpm)])


def manual_off(fan_idx: int = 1) -> tuple[bool, str]:
    backend = get_backend()
    if backend == "thinkpad":
        return _run_helper(["set-thinkpad-fan", "auto"])
    elif backend == "asus_wmi":
        return _run_helper(["set-asus-profile", "0"])
    elif backend == "dell":
        return _run_helper(["set-dell-profile", "balanced"])
    elif backend == "hwmon_pwm":
        pwm = find_generic_pwm()
        if pwm:
            hw_name, pwm_idx = pwm
            return _run_helper(["set-pwm-enable", hw_name, str(pwm_idx), "2"])
    elif backend == "macsmc":
        return _run_helper(["manual-off-macsmc", str(fan_idx)])
    return _run_helper(["manual-off", str(fan_idx)])


def set_manual_rpm(rpm: int, fan_idx: int = 1) -> tuple[bool, str]:
    backend = get_backend()
    if backend in ("thinkpad", "asus_wmi", "dell", "hwmon_pwm", "macsmc"):
        return manual_on(rpm, fan_idx)
    return _run_helper(["set-fan-output", str(fan_idx), str(rpm)])
