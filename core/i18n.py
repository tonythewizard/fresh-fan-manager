def tr(key: str, default: Optional[str] = None, **kwargs: Any) -> str:
    """Translate a key into the active language, with optional formatting."""
    entry = TRANSLATIONS.get(key)
    if entry is not None:
        text = entry.get(_CURRENT_LANG) or entry.get("en") or (default or key)
    else:
        text = default or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
